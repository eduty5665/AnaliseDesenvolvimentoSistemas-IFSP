    private void cleanAndResetForm() {
        txfName.setText("");
        txfEmail.setText("");
        txfPhone.setText("");
        txfPassword.setText("");
        txfPasswordConfirm.setText("");
        txfId.setText("");

        // limpa dados de atulização
        isUpdate = false;

        // ajusta o botão da salvar
        btnUserCreate.setIcon(
                new javax.swing.ImageIcon(
                        getClass().getResource("/icons/add.png")
                )
        );
    }

    private void btnUserCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUserCreateActionPerformed
        // TODO add your handling code here:

        user = new User();

        if (isUpdate) {
            user.setId(userUpdate.getId());
        }
        user.setName(txfName.getText());
        user.setEmail(txfEmail.getText());
        user.setPassword(String.copyValueOf(txfPassword.getPassword()));
        user.setPhone(txfPhone.getText().replaceAll("[^0-9]", ""));
        user.setPermission(cbxPermission.isSelected());

        UserService service = new UserService();
        String result = service.saveUser(user);

        if (result.equals("SUCESSO")) {
            JOptionPane.showMessageDialog(this, "Cliente salvo com sucesso!");
            cleanAndResetForm();
            listClientsInTable();
        } else {
            JOptionPane.showMessageDialog(this, result, "Erro de Validação", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnUserCreateActionPerformed

    private void listClientsInTable() {
        usersList = new ArrayList<>();

        model = (DefaultTableModel) tableDataUser.getModel();
        model.setNumRows(0);
        model.setColumnIdentifiers(new Object[]{"ID", "PERMISSÃO", "NOME", "EMAIL", "PHONE"});

        usersList = new UserController().list();

        if (!usersList.isEmpty()) {
            for (User u : usersList) {
                model.addRow(new Object[]{
                    u.getId(),
                    u.getPermission(),
                    u.getName(),
                    u.getEmail(),
                    Mask.maskPhone(u.getPhone()),});
                System.out.println("Usuario: " + u.toString());
            }
        }
    }

