    private void btnUserDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUserDeleteActionPerformed
        // TODO add your handling code here:
        if (userUpdate.getId() <= 0) {
            JOptionPane.showMessageDialog(this, "Selecione o usuario na tabela para excluir!", "Atenção!", JOptionPane.QUESTION_MESSAGE);
            return;
        }

        var option = JOptionPane.showInternalConfirmDialog(
                this, "Esssa alteração não tem reversão, deseja continuar?",
                "Excluir regostro",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (JOptionPane.YES_OPTION != option) {
            return;
        }

        System.out.println("Excluir usuario id: " + userUpdate.getId());
        UserService uService = new UserService();
        String result = uService.delete(userUpdate.getId());
        if(result.equals("SUCESSO")){
            JOptionPane.showMessageDialog(this, "Usuário deletado com sucesso!");
            cleanAndResetForm();
        }else{
            JOptionPane.showMessageDialog(this, "Erro de validação");
        }

    }//GEN-LAST:event_btnUserDeleteActionPerformed

