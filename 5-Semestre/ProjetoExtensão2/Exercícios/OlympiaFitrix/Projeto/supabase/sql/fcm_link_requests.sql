alter table public.personal
add column if not exists fcm_token text;

alter table public.alunos
add column if not exists fcm_token text;

create table if not exists public.solicitacao_vinculo (
    id_solicitacao bigint generated by default as identity primary key,
    id_aluno bigint not null references public.alunos(id_aluno),
    id_personal bigint not null references public.personal(id_personal),
    status text not null default 'pendente',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_solicitacao_vinculo_personal_status
on public.solicitacao_vinculo(id_personal, status);

create index if not exists idx_solicitacao_vinculo_aluno_status
on public.solicitacao_vinculo(id_aluno, status);

create unique index if not exists uq_solicitacao_vinculo_aluno_pendente
on public.solicitacao_vinculo(id_aluno)
where status = 'pendente';
