"""### Instanciando e treinando o classificador
Mantemos `clf`, como no original. `criterion='entropy'` permite relacionar a aula com entropia e ganho de informação; o original utilizava o padrão Gini.
- `max_depth`: profundidade máxima;
- `min_samples_split`: mínimo de amostras para tentar dividir um nó;
- `min_samples_leaf`: mínimo de amostras em cada folha;
- `random_state`: permite reproduzir o treinamento.

Os limites abaixo são escolhas didáticas, não parâmetros otimizados. Não ajustar repetidamente usando os resultados do teste; em um projeto real, usar validação separada ou validação cruzada no treino.

"""

