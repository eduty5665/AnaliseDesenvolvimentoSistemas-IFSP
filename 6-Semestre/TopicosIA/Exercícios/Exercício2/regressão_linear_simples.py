def interpretar_r2(valor):
    if valor >= 0.90:
        return "excelente capacidade explicativa"
    elif valor >= 0.70:
        return "boa capacidade explicativa"
    elif valor >= 0.50:
        return "capacidade explicativa moderada"
    else:
        return "baixa capacidade explicativa"

def interpretar_mape(valor):
    if valor < 10:
        return "excelente precisão"
    elif valor < 20:
        return "boa precisão"
    elif valor < 50:
        return "precisão razoável"
    else:
        return "baixa precisão"

def interpretar_overfitting(r2_treino, r2_teste):
    diferenca = r2_treino - r2_teste
    if diferenca < 0.05:
        return "não há indícios relevantes de overfitting"
    elif diferenca < 0.15:
        return "há leves indícios de overfitting"
    else:
        return "há fortes indícios de overfitting"

print(f"R² Treino: {r2_treino:.2f}")
print(f"Interpretação: O modelo apresentou {interpretar_r2(r2_treino)} nos dados de treinamento.")

print(f"\nR² Teste : {r2_teste:.2f}")
print(f"Interpretação: O modelo apresentou {interpretar_r2(r2_teste)} em dados não vistos, indicando sua capacidade de generalização.")

print(f"\nDiferença entre R² de treino e teste: {r2_treino - r2_teste:.2f}")
print(f"Interpretação: {interpretar_overfitting(r2_treino, r2_teste)}.")

print(f"\nMAE : {mae:.2f}")
print(f"Interpretação: Em média, o modelo erra aproximadamente {mae:.2f} unidades da variável alvo por previsão.")

print(f"\nMSE : {mse:.2f}")
print("Interpretação: O erro quadrático médio penaliza mais fortemente erros maiores, sendo útil para destacar previsões muito distantes do valor real.")

print(f"\nRMSE: {rmse:.2f}")
print(f"Interpretação: O erro médio das previsões é de aproximadamente {rmse:.2f} unidades da variável alvo, na mesma escala dos dados originais.")

print(f"\nMAPE: {mape:.2f}%")
print(f"Interpretação: O modelo apresentou {interpretar_mape(mape)}, com erro percentual médio de {mape:.2f}%.")

print("\nConclusão Geral:")
print(f"O modelo apresentou {interpretar_r2(r2_teste)} no conjunto de teste e {interpretar_mape(mape)}.")
print(f"Além disso, {interpretar_overfitting(r2_treino, r2_teste)}, o que ajuda a avaliar o equilíbrio entre aprendizado e generalização.")

