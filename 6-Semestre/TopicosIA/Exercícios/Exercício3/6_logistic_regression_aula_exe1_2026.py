import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
import pickle

SEED = 42

from google.colab import drive
drive.mount('/content/drive')

"""## Importando o dataset"""

dataset = pd.read_csv('/content/drive/MyDrive/Lab_IA/Dataset/Social_Network_Ads.csv')

dataset

print("\n=== VALORES NULOS (%) ===")
print((dataset.isna().mean() * 100).round(2))

# Padronizando a variável categórica Gender
dataset["Gender"] = dataset["Gender"].map({"Female": 1, "Male": 0}).astype("Int64")

print("\n=== GENDER CODIFICADO ===")
print(dataset["Gender"].head(10))

# Separando X e y
X = dataset[["Gender", "Age", "EstimatedSalary"]]
y = dataset["Purchased"]

print(X.head())

print(y.head())

# Visualização dos dados

compra = dataset[dataset['Purchased'] == 1]
n_compra = dataset[dataset['Purchased'] == 0]

fig, ax = plt.subplots(figsize=(8, 4))
ax.plot(compra['Age'], compra['EstimatedSalary'], '+b', label='Comprou')
ax.plot(n_compra['Age'], n_compra['EstimatedSalary'], '*r', label='Não comprou')
plt.xlabel('Idade')
plt.ylabel('Salário Estimado Anual')
plt.legend()
plt.show()

print("\n=== DISTRIBUIÇÃO DO ALVO ===")
print(y.value_counts(normalize=True).round(3))

#  Dividindo em treino e teste
from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=SEED, stratify=y)

print("\nFormato X_train:", X_train.shape)
print("Formato X_test :", X_test.shape)
print("Formato y_train:", y_train.shape)
print("Formato y_test :", y_test.shape)

# Feature Scaling
from sklearn.preprocessing import StandardScaler

sc_X = StandardScaler()

X_train = sc_X.fit_transform(X_train)
X_test = sc_X.transform(X_test)

print("\n=== X_train PADRONIZADO ===")
print(X_train[:5])

# Treinando o modelo Logistic Regression

from sklearn.linear_model import LogisticRegression

classifier = LogisticRegression(random_state=SEED)
classifier.fit(X_train, y_train)

print("\n=== COEFICIENTES ===")
print(classifier.coef_)

print("\n=== INTERCEPTO ===")
print(classifier.intercept_)

# Predizendo os valores

y_pred = classifier.predict(X_test)
y_prob = classifier.predict_proba(X_test)

print("\n=== PREDIÇÕES ===")
print(y_pred[:10])

print("\n=== PROBABILIDADES DAS CLASSES ===")
print(y_prob[:10])

# Matriz de confusão e métricas

from sklearn.metrics import (confusion_matrix, accuracy_score, precision_score, recall_score, f1_score, classification_report)

cm = confusion_matrix(y_test, y_pred)

cm

# MATRIZ DE CONFUSÃO

acuracia = accuracy_score(y_test, y_pred)
precisao = precision_score(y_test, y_pred)
recall = recall_score(y_test, y_pred)
f1 = f1_score(y_test, y_pred)

print("\n=== MÉTRICAS ===")
print(f"Acurácia : {acuracia:.4f}")
print(f"Precisão : {precisao:.4f}")
print(f"Recall   : {recall:.4f}")
print(f"F1-Score : {f1:.4f}")

"""1. Acurácia = 0.81 (81%)

Percentual total de acertos

Parece bom, mas…

Problema:

Pode ser enganosa se houver desbalanceamento

Exemplo:

80% dos dados = "normal"
Modelo prevê sempre "normal" → já dá ~80%

------------------------------------------------------------

2. Precisão = 0.8148 (81%)

Quando o modelo diz “é positivo”, ele acerta 81%

Significa:

Poucos falsos positivos

Interpretação:

O modelo é confiável quando acusa um problema.

-------------------------------------------------------------

3. Recall = 0.6111 (61%)

Dos positivos reais, ele detecta apenas 61%

Problema sério:

Está deixando passar ~39% dos casos positivos

Interpretação:

O modelo perde muitos casos importantes
"""

# RELATÓRIO DE CLASSIFICAÇÃO

print(classification_report(y_test, y_pred))

# Comparação entre valores reais e preditos
resultado = pd.DataFrame({
    "Real": y_test.values,
    "Predito": y_pred
})

print(resultado.head(15))

