# Importando as Bibliotecas
import numpy as np
import pandas as pd
import pickle

from google.colab import drive
drive.mount('/content/drive')

#Lendo o Modelo no Disco
filename_modelo = '/content/drive/MyDrive/Lab_IA/Dataset/classificador_logistico.sav'
filename_scaler = '/content/drive/MyDrive/Lab_IA/Dataset/scaler_logistico.sav'

classifier = pickle.load(open(filename_modelo, 'rb'))
sc_X = pickle.load(open(filename_scaler, 'rb'))

print("Modelo e scaler carregados com sucesso.")

"""## Entrada do usuário"""

print("\n=== ENTRADA DE DADOS ===")
genero = input("Informe o gênero (Male/Female): ").strip()
idade = input("Informe a idade: ").strip()
salario = input("Informe o salário estimado: ").strip()

"""##  Tratando os valores informados"""

if genero.lower() == "female":
    genero = 1
elif genero.lower() == "male":
    genero = 0
else:
    raise ValueError("Valor inválido para gênero. Use 'Male' ou 'Female'.")

idade = float(idade)
salario = float(salario)

"""## Montando os dados no formato correto"""

New_X_test = pd.DataFrame({
    "Gender": [genero],
    "Age": [idade],
    "EstimatedSalary": [salario]
})

print("\n=== DADOS INFORMADOS ===")
print(New_X_test)

"""## Aplicando o mesmo scaler do treinamento"""

New_X_test_escalado = sc_X.transform(New_X_test)

print("\n=== DADOS ESCALADOS ===")
print(New_X_test_escalado)

""" ## Fazendo a predição"""

y_pred = classifier.predict(New_X_test_escalado)
y_prob = classifier.predict_proba(New_X_test_escalado)

print("\n=== RESULTADO DA PREDIÇÃO ===")
print("Classe prevista:", y_pred[0])
print("Probabilidades [Não compra, Compra]:", y_prob[0])

"""## Interpretação do resultado"""

if y_pred[0] == 0:
    print("\nResultado: Não compraria.")
else:
    print("\nResultado: Sim, compraria.")