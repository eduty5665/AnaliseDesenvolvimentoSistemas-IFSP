"""## 6. Tratamento de valores ausentes

Existem várias estratégias para lidar com dados ausentes.  
Neste exemplo, vamos preencher com a **mediana**, pois ela é mais robusta a outliers do que a média.
"""

# Cria uma cópia do DataFrame para preservar o original
