"""## 7. Detecção de outliers com IQR

Uma técnica muito comum para detectar outliers é usar o **Intervalo Interquartil (IQR)**.

Regra:
- abaixo de `Q1 - 1.5 * IQR`
- acima de `Q3 + 1.5 * IQR`

Exemplos:

Exemplo:

Q1 = 20
Q3 = 30

Então:

IQR = 30 - 20 = 10

Limites:

Inferior = 20 - (1.5 × 10) = 5

Superior = 30 + (1.5 × 10) = 45
"""

# Define uma função para detectar outliers pelo método do IQR
def detectar_outliers_iqr(serie):
    # Calcula o primeiro quartil
    q1 = serie.quantile(0.25)
    # Calcula o terceiro quartil
    q3 = serie.quantile(0.75)
    # Calcula o IQR
    iqr = q3 - q1
    # Calcula o limite inferior
    limite_inferior = q1 - 1.5 * iqr
    # Calcula o limite superior
    limite_superior = q3 + 1.5 * iqr
    # Retorna uma máscara booleana dos outliers
    return (serie < limite_inferior) | (serie > limite_superior)

# Detecta outliers em cada coluna numérica
out_temp = detectar_outliers_iqr(df_limpo['temperatura'])
out_umid = detectar_outliers_iqr(df_limpo['umidade'])
out_co2 = detectar_outliers_iqr(df_limpo['co2'])

# Mostra quantos outliers foram encontrados por coluna
print('Outliers em temperatura:', out_temp.sum())
print('Outliers em umidade:', out_umid.sum())
print('Outliers em co2:', out_co2.sum())

# Mostra as linhas que possuem pelo menos um outlier
df_limpo[out_temp | out_umid | out_co2]

"""## 8. Remoção de outliers

Vamos **remover** os outliers detectados. Em aplicações reais, isso deve ser feito com critério, pois um outlier pode ser erro ou pode ser um evento raro importante.
"""

# Cria uma máscara que identifica linhas sem outliers nas três variáveis
