print(dataset["Pais"].value_counts(dropna=False))

print("\nCrosstab Pais x Comprou:")
print(pd.crosstab(dataset["Pais"], dataset["Comprou"], dropna=False, margins=True))

# Estatísticas numéricas
print("\nDescribe (numericas):")
print(dataset[["Idade","Salario"]].describe())

# Histogramas e Boxplots (rápidos)
fig, axes = plt.subplots(1, 2, figsize=(10,4))
dataset["Idade"].hist(ax=axes[0]); axes[0].set_title("Histograma - Idade")
