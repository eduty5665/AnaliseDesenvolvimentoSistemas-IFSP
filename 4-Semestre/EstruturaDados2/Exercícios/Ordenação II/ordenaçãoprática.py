# Testes no vetor pequeno
print("----- Testes no Vetor Pequeno -----")
df_pequeno = testar_algoritmos(vetor_pequeno)
mostrar_resultados(df_pequeno, "Tempo de Execução - Vetor Pequeno (10 elementos)")

# Testes no vetor médio
print("\n----- Testes no Vetor Médio -----")
df_medio = testar_algoritmos(vetor_medio)
